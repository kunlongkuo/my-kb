#!/usr/bin/env python3
"""Build the skill's references/ from the rule files in rules/ (the single source of truth).

Run from anywhere:  python3 skills/ve-director/scripts/build_refs.py
Edit rules in skills/ve-director/rules/, never in references/ — it is regenerated.
"""
import re
import sys
from pathlib import Path

SKILL = Path(__file__).resolve().parent.parent
SOURCES = SKILL / "rules"
REFS = SKILL / "references"
BANNER = "<!-- GENERATED by scripts/build_refs.py from skills/ve-director/rules — do not edit here -->\n\n"


def sections(fn, level, prefixes):
    text = (SOURCES / fn).read_text(encoding="utf-8")
    parts = re.split(r"(?m)^(?=%s )" % ("#" * level), text)
    out = []
    for x in prefixes:
        hits = [p for p in parts if p.splitlines() and p.splitlines()[0].startswith(x)]
        if len(hits) != 1:
            sys.exit(f"build_refs: {fn}: expected 1 section starting '{x}', found {len(hits)}")
        out.append(hits[0].rstrip() + "\n")
    return out


def between(fn, start_re, end_re):
    text = (SOURCES / fn).read_text(encoding="utf-8")
    m = re.search(r"(?ms)^%s.*?(?=^%s)" % (start_re, end_re), text)
    if not m:
        sys.exit(f"build_refs: {fn}: block '{start_re}' not found")
    return m.group(0).rstrip() + "\n"


def write(rel, title, blocks):
    path = REFS / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    body = BANNER + f"# {title}\n\n" + "\n".join(blocks)
    path.write_text(body, encoding="utf-8")
    return rel, len(body.encode())


def main():
    built = []
    built.append(write("plan-rules.md", "Planning rules (duration, density, frozen world, domain, tone)",
        ["## FROM 01-core.md\n"] + sections("01-core.md", 2, ["## §6 ", "## §7 ", "## §9 ", "## §11 "])
        + ["## FROM 00-operating-manual.md\n", "## Actor cap\n"] + sections("00-operating-manual.md", 3, ["### Step 1.6"])
        + ["## FROM 03-domains.md\n"] + sections("03-domains.md", 2,
            ["## narrative-character", "## narrative-scene", "## Tier 2", "## Tone axis"])
        + ["## FROM 07-experimental.md\n"] + sections("07-experimental.md", 2, ["## §1 "])))

    built.append(write("render-rules.md", "Rendering rules (output contract, locks, VE v3.5 grammar, minimal format)",
        ["## FROM 00-operating-manual.md\n"] + sections("00-operating-manual.md", 2, ["## §2", "## §3", "## §4"])
        + ["## FROM 01-core.md\n"] + sections("01-core.md", 2,
            ["## §1 ", "## §2 ", "## §5 ", "## §8 ", "## §10 ", "## §11 "])
        + ["## FROM 02-modes.md\n"] + sections("02-modes.md", 3,
            ["### §0.1", "### §0.2", "### §1.1", "### §1.2 ", "### §1.2a", "### §1.3",
             "### §4.1", "### §4.2", "### §4.3", "### §4.4"])
        + ["## FROM 04-platform-videoexpress.md\n"] + sections("04-platform-videoexpress.md", 2,
            ["## Platform-Specific Rules", "## Multi-shot narrative continuity"])
        + [between("04-platform-videoexpress.md", "#### Pitfall 5", "#### Pitfall 6")]
        + ["## FROM 05-ve35-animation-styles.md\n"] + sections("05-ve35-animation-styles.md", 2, ["## §1 "])
        + ["## FROM 07-experimental.md\n"] + sections("07-experimental.md", 2, ["## §2 "])))

    built.append(write("dialogue.md", "Dialogue rules (load only when the idea has spoken lines)",
        sections("01-core.md", 2, ["## §3 "])))

    # One file per official v3.5 style: its table row + its verbatim official example.
    table = sections("05-ve35-animation-styles.md", 2, ["## §2 "])[0]
    header = [l for l in table.splitlines() if l.startswith("| mediaType") or l.startswith("|---")]
    rows = {m.group(1): l for l in table.splitlines() if (m := re.match(r"^\| `([a-z0-9-]+)` \|", l))}
    text05 = (SOURCES / "05-ve35-animation-styles.md").read_text(encoding="utf-8")
    for sid, row in rows.items():
        m = re.search(r"(?ms)^### [^\n]*\(`%s`\)\n.*?(?=^### |^## |\Z)" % re.escape(sid), text05)
        if not m:
            sys.exit(f"build_refs: no official example for style '{sid}'")
        built.append(write(f"styles/{sid}.md", f"Style: {sid}",
            ["## Style row (05 §2)\n", "\n".join(header + [row]) + "\n", "## Official example (05 §3)\n", m.group(0)]))
    built.append(write("styles/live.md", "Style: live (photoreal)", sections("02-modes.md", 3, ["### §4.5"])))

    built.append(write("handbooks/classical.md", "Handbook: classical / period narrative",
        [(SOURCES / "06-director-classical.md").read_text(encoding="utf-8")]))

    for rel, n in built:
        print(f"{n:7d}  references/{rel}")


if __name__ == "__main__":
    main()
